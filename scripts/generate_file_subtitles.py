"""Compile AUDIO4/5/6 SRT and opening text into one shared 1024x9 ROM."""
import argparse
import hashlib
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RTL = ROOT / 'src/user_source/hdl_source/SD'
TOTALS = {4: 3079722, 5: 3118884, 6: 3242676}


def load_cues(number):
    def samples(timestamp):
        h, m, s, ms = map(int, re.split('[:,]', timestamp))
        return ((h * 3600 + m * 60 + s) * 1000 + ms) * 48
    cues = []
    for block in re.split(r'\n\s*\n', (ROOT / f'assets/AUDIO{number}.srt').read_text(encoding='utf-8-sig').strip()):
        lines = block.splitlines()
        start, end = map(samples, lines[1].split(' --> '))
        text = ''.join(lines[2:])
        if not 0 <= start < end <= TOTALS[number] or not 1 <= len(text) <= 40:
            raise ValueError(f'AUDIO{number}: invalid cue time/length')
        cues.append((start, end, text))
    paragraph = ROOT / ('assets/subtitle.txt' if number == 4 else f'assets/AUDIO{number}.txt')
    if len(cues) != 8 or ''.join(c[2] for c in cues) != paragraph.read_text(encoding='utf-8-sig').strip():
        raise ValueError(f'AUDIO{number}: eight cues must match TXT exactly')
    if any(cues[i][1] > cues[i+1][0] for i in range(7)):
        raise ValueError(f'AUDIO{number}: overlapping cues')
    return cues


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--pcm', type=Path, help='Validate AUDIO4 PCM (legacy option)')
    parser.add_argument('--card', type=Path, help='Validate all three PCM files on this card')
    args = parser.parse_args()
    for number, total in TOTALS.items():
        pcm = args.card / f'AUDIO{number}.PCM' if args.card else args.pcm if number == 4 else None
        if pcm:
            data = pcm.read_bytes()
            if len(data) != total * 2:
                parser.error(f'AUDIO{number} length changed: update sample total and SRT')
            print(f'AUDIO{number} PCM SHA256: {hashlib.sha256(data).hexdigest()}')
    font = (RTL / 'subtitle_font.v').read_text(encoding='utf-8')
    ids = {chr(i): i for i in range(32, 127)}
    ids.update({chr(int(c,16)): int(i,16) for c,i in re.findall(r"16'h([0-9a-f]+): glyph=9'h([0-9a-f]+)", font)})
    words, metadata, bases = [], [], []
    for track, number in enumerate(TOTALS):
        text = []
        for cue, (start, end, sentence) in enumerate(load_cues(number)):
            bases.append((track*8+cue, len(text)))
            metadata.append((track*8+cue,start,end,len(sentence)))
            text.extend(ids[c] for c in sentence)
        if len(text) > 256:
            parser.error(f'AUDIO{number}: text exceeds 256 glyphs')
        words.extend(text + [32]*(256-len(text)))
        print(f'AUDIO{number}: 8 cues, {len(text)} characters, {TOTALS[number]/48000:.6f}s')
    opening = (ROOT / 'assets/opening.txt').read_text(encoding='utf-8-sig').splitlines()
    if len(opening) != 6 or any(len(line)>32 for line in opening):
        parser.error('Opening requires six lines, at most 32 characters each')
    words.extend(ids[opening[i//32][i%32]] if i//32<6 and i%32<len(opening[i//32]) else 32 for i in range(256))
    out = ['// Generated by scripts/generate_file_subtitles.py. Shared SRT/opening ROM.',
           'module audio4_subtitle_data(input wire clk, input wire [1:0] track, text_track,',
           '    input wire [2:0] cue, text_cue, input wire [5:0] position,',
           '    input wire opening, input wire [7:0] opening_address,',
           '    output reg [8:0] glyph, output reg [21:0] start_sample, end_sample,',
           '    output reg [5:0] length, output reg [21:0] total_samples);',
           '    reg [7:0] base;',
           '    reg [8:0] text_rom [0:1023]; /* fehdl force_ram=1, ram_style="bram" */',
           '    initial begin']
    out.extend(f"        text_rom[{i}]=9'h{word:03x};" for i,word in enumerate(words))
    out += ['    end', '    wire [7:0] offset=base+position;',
            "    wire [9:0] address=opening ? {2'd3,opening_address} : {text_track,offset};",
            '    always @(posedge clk) glyph<=text_rom[address];',
            '    always @* begin', '        case(track)']
    out.extend(f"            2'd{track}: total_samples=22'd{TOTALS[number]};" for track,number in enumerate(TOTALS))
    out += ["            default: total_samples=22'd3079722;", '        endcase', '        case({track,cue})']
    out.extend(f"            5'd{key}: begin start_sample=22'd{start}; end_sample=22'd{end}; length=6'd{length}; end" for key,start,end,length in metadata)
    out += ['            default: begin start_sample=0; end_sample=0; length=0; end', '        endcase', '        case({text_track,text_cue})']
    out.extend(f"            5'd{key}: base=8'd{base};" for key,base in bases)
    out += ['            default: base=0;', '        endcase', '    end', 'endmodule', '']
    (RTL / 'audio4_subtitle_data.v').write_text('\n'.join(out), encoding='utf-8')


if __name__ == '__main__':
    main()
