"""Compile the AUDIO4 SRT against the shared glyph map; no runtime SRT parser."""
import argparse
import hashlib
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RTL = ROOT / 'src/user_source/hdl_source/SD'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--pcm', type=Path, help='Validate the exact 48kHz mono PCM used by this timeline')
    args = parser.parse_args()
    total_samples = 3079722
    if args.pcm:
        data = args.pcm.read_bytes()
        if len(data) != total_samples * 2:
            parser.error('AUDIO4 length changed: update timeline duration before regenerating')
        print('AUDIO4 PCM SHA256:', hashlib.sha256(data).hexdigest())
    font = (RTL / 'subtitle_font.v').read_text(encoding='utf-8')
    ids = {chr(i): i for i in range(32, 127)}
    ids.update({chr(int(c, 16)): int(i, 16) for c, i in
                re.findall(r"16'h([0-9a-f]+): glyph=8'h([0-9a-f]+)", font)})
    cues = []
    def samples(timestamp):
        h, m, s, ms = map(int, re.split('[:,]', timestamp))
        return ((h * 3600 + m * 60 + s) * 1000 + ms) * 48
    for block in (ROOT / 'assets/AUDIO4.srt').read_text(encoding='utf-8-sig').strip().split('\n\n'):
        lines = block.splitlines()
        start, end = map(samples, lines[1].split(' --> '))
        text = ''.join(lines[2:])
        if not 0 <= start < end <= total_samples or not 1 <= len(text) <= 40:
            parser.error('Invalid cue time/length')
        cues.append((start, end, text))
    paragraph = (ROOT / 'assets/subtitle.txt').read_text(encoding='utf-8-sig').strip()
    if len(cues) != 8 or ''.join(c[2] for c in cues) != paragraph:
        parser.error('SRT must have eight cues matching subtitle.txt exactly')
    if any(cues[i][1] > cues[i+1][0] for i in range(7)):
        parser.error('Overlapping cues')
    glyphs = []
    bases = []
    for _, _, text in cues:
        bases.append(len(glyphs))
        glyphs.extend(ids[c] for c in text)
    if len(glyphs) > 256:
        parser.error('Text exceeds 256 glyphs')
    out = ['// Generated by scripts/generate_audio4_subtitle.py.',
           'module audio4_subtitle_data(input wire clk, input wire [2:0] cue, text_cue,',
           '    input wire [5:0] position, output reg [7:0] glyph,',
           '    output reg [21:0] start_sample, end_sample,',
           '    output reg [5:0] length, output wire [21:0] total_samples);',
           f"    assign total_samples=22'd{total_samples};",
           '    reg [7:0] base;',
           '    reg [7:0] text_rom [0:255]; /* fehdl force_ram=1, ram_style="bram" */',
           '    initial begin']
    for i in range(256):
        out.append(f"        text_rom[{i}]=8'h{glyphs[i] if i<len(glyphs) else 32:02x};")
    out += ['    end', '    wire [7:0] address=base+position;',
            '    always @(posedge clk) glyph<=text_rom[address];', '    always @* begin', '        case(cue)']
    for i, (start, end, text) in enumerate(cues):
        out.append(f"            3'd{i}: begin start_sample=22'd{start}; end_sample=22'd{end}; length=6'd{len(text)}; end")
    out += ["            default: begin start_sample=0; end_sample=0; length=0; end",
            '        endcase', '        case(text_cue)']
    for i, base in enumerate(bases):
        out.append(f"            3'd{i}: base=8'd{base};")
    out += ['            default: base=0;', '        endcase', '    end', 'endmodule', '']
    (RTL / 'audio4_subtitle_data.v').write_text('\n'.join(out), encoding='utf-8')
    print(f'Generated 8 cues, {len(glyphs)} characters, {total_samples/48000:.6f}s PCM')


if __name__ == '__main__':
    main()
