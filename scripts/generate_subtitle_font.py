"""Generate the project's compact 16x16 subtitle ROM (Pillow required).

Generated Verilog contains its own initialization: no runtime .mem path needed.
Only the supplied Chinese characters are included; printable ASCII is complete.
"""
import argparse
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'src/user_source/hdl_source/SD/subtitle_font.v'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--text', type=Path, default=ROOT / 'assets/subtitle.txt')
    parser.add_argument('--extra', type=Path, help='UTF-8 text containing additional runtime characters')
    parser.add_argument('--font', default='C:/Windows/Fonts/simsun.ttc')
    parser.add_argument('--output', type=Path, default=OUT)
    parser.add_argument('--preview', type=Path, help='Optional PNG glyph atlas for inspection')
    args = parser.parse_args()
    text = args.text.read_text(encoding='utf-8-sig').strip()
    if not text or any(ord(c) < 32 for c in text) or len(text) > 256:
        parser.error('Default text must be a single line of 1..256 printable characters')
    extra = args.extra.read_text(encoding='utf-8-sig') if args.extra else ''
    chinese = sorted({c for c in text + extra if ord(c) >= 127})
    if len(chinese) > 161 or any(ord(c) > 65535 for c in chinese):
        parser.error('At most 161 distinct additional BMP Unicode characters are supported')
    glyphs = {i: chr(i) for i in range(32, 127)}
    # Reuse unused control-code IDs after 128..255; printable ASCII stays intact.
    extra_ids = list(range(128, 256)) + list(range(32)) + [127]
    glyphs.update({extra_ids[i]: c for i, c in enumerate(chinese)})
    ids = {c: i for i, c in glyphs.items()}
    # A synchronous, initialized ROM, rather than a wide combinational glyph mux.
    lines = ['// Generated by scripts/generate_subtitle_font.py; do not edit.',
             '// 16x16, MSB is leftmost. ASCII IDs match ASCII; extra IDs start at 128.',
             'module subtitle_font_rom (input wire clk, input wire [11:0] address,',
             '    output reg [15:0] row);',
             '    reg [15:0] pixels [0:4095]; /* fehdl force_ram=1, ram_style="bram" */',
             '    initial begin']
    font = ImageFont.truetype(args.font, 16)
    atlas = Image.new('RGB', (16 * 40, 16 * 40), '#202830')
    atlas_draw = ImageDraw.Draw(atlas)
    for i in range(256):
        tile = Image.new('L', (16, 16))
        if i in glyphs:
            draw = ImageDraw.Draw(tile)
            bounds = draw.textbbox((0, 0), glyphs[i], font=font)
            draw.text(((16 - (bounds[2] - bounds[0])) // 2 - bounds[0],
                       (16 - (bounds[3] - bounds[1])) // 2 - bounds[1]),
                      glyphs[i], font=font, fill=255)
        tile = tile.point(lambda p: 255 if p >= 96 else 0)
        for y in range(16):
            bits = sum((1 << (15 - x)) for x in range(16) if tile.getpixel((x, y)))
            lines.append(f"        pixels[{i * 16 + y}]=16'h{bits:04x};")
        if i in glyphs:
            pos = ((i % 16) * 40, (i // 16) * 40)
            atlas.paste(tile.convert('RGB'), (pos[0] + 12, pos[1] + 3))
            atlas_draw.text((pos[0] + 8, pos[1] + 22), f'{i:02X}', fill='white')
    lines += ['    end', '    always @(posedge clk) row<=pixels[address];', 'endmodule', '',
              'module subtitle_unicode_map (input wire [15:0] codepoint, output reg [7:0] glyph);',
              '    always @* begin', "        glyph=8'h3f;", "        if(codepoint>=32 && codepoint<=126) glyph=codepoint[7:0];",
              '        else case(codepoint)']
    for c in chinese:
        lines.append(f"            16'h{ord(c):04x}: glyph=8'h{ids[c]:02x}; // {c}")
    lines += ["            default: glyph=8'h3f;", '        endcase', '    end', 'endmodule', '',
              'module subtitle_default_text (input wire clk, input wire [7:0] address,',
              '    output reg [7:0] glyph, output wire [8:0] length);',
              f"    assign length=9'd{len(text)};", '    always @(posedge clk) begin', '        case(address)']
    for i, c in enumerate(text):
        lines.append(f"            8'd{i}: glyph<=8'h{ids[c]:02x}; // {c}")
    lines += ["            default: glyph<=8'h20;", '        endcase', '    end', 'endmodule', '']
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text('\n'.join(lines), encoding='utf-8')
    if args.preview:
        atlas.save(args.preview)
    print(f'Generated {args.output}: {len(text)} default characters, {len(chinese)} extra glyphs, ASCII 32..126, 65536 font bits')


if __name__ == '__main__':
    main()
