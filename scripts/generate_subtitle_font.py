"""Generate the project's compact 16x16 subtitle ROM (Pillow required).

Generated Verilog contains its own initialization: no runtime .mem path needed.
Only the supplied Chinese characters are included; printable ASCII is complete.
"""
import argparse
import re
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'src/user_source/hdl_source/SD/subtitle_font.v'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--text', type=Path, default=ROOT / 'assets/product_20261027/AUDIO2.txt')
    parser.add_argument('--extra', type=Path, action='append', default=[], help='Additional UTF-8 text; repeat for multiple files')
    parser.add_argument('--font', default='C:/Windows/Fonts/simsun.ttc')
    parser.add_argument('--output', type=Path, default=OUT)
    parser.add_argument('--preview', type=Path, help='Optional PNG glyph atlas for inspection')
    parser.add_argument('--preserve-map', type=Path, help='Keep existing IDs used by compiled SRT data')
    parser.add_argument('--opening', type=Path, help='Six UTF-8 opening-animation text lines')
    args = parser.parse_args()
    text = args.text.read_text(encoding='utf-8-sig').strip()
    if not text or any(ord(c) < 32 for c in text) or len(text) > 256:
        parser.error('Default text must be a single line of 1..256 printable characters')
    extra = ''.join(p.read_text(encoding='utf-8-sig') for p in args.extra)
    opening = args.opening.read_text(encoding='utf-8-sig').splitlines() if args.opening else []
    if opening and (len(opening) != 6 or any(len(s)>32 for s in opening)):
        parser.error('Opening requires six lines of at most 32 characters')
    extra += ''.join(opening)
    preserved = {}
    if args.preserve_map:
        preserved = {chr(int(c,16)): int(i,16) for c,i in re.findall(
            r"16'h([0-9a-f]+): glyph=[89]'h([0-9a-f]+)", args.preserve_map.read_text(encoding='utf-8'))}
        extra += ''.join(preserved)
    chinese = sorted({c for c in text + extra if ord(c) >= 127})
    if len(chinese) > 417 or any(ord(c) > 65535 for c in chinese):
        parser.error('At most 417 distinct additional BMP Unicode characters are supported')
    glyphs = {i: chr(i) for i in range(32, 127)}
    # Reuse unused control-code IDs after 128..255; printable ASCII stays intact.
    extra_ids = list(range(128, 256)) + list(range(32)) + [127] + list(range(256,512))
    free_ids = iter(i for i in extra_ids if i not in preserved.values())
    glyphs.update({preserved[c] if c in preserved else next(free_ids): c for c in chinese})
    ids = {c: i for i, c in glyphs.items()}
    # A synchronous, initialized ROM, rather than a wide combinational glyph mux.
    slots = max(256,max(glyphs)+1)
    # Power-of-two banks avoid TD's inefficient mapping of a 6864-row ROM.
    # Keep a single synchronous read latency, including the bank selector.
    remaining = slots*16
    banks = []
    while remaining > 0:
        size = 1 << (remaining.bit_length()-1)
        if remaining <= 1024:
            size = 1 << (remaining-1).bit_length()
        if size < 512:
            size = 512
        banks.append(size)
        remaining -= size
    bank_offsets = []
    base = 0
    for size in banks:
        bank_offsets.append(base)
        base += size
    lines = ['// Generated by scripts/generate_subtitle_font.py; do not edit.',
             '// 16x16, MSB is leftmost. ASCII IDs match ASCII; extra IDs start at 128.',
             'module subtitle_font_rom (input wire clk, input wire [12:0] address,',
             '    output wire [15:0] row);']
    for bank, size in enumerate(banks):
        lines += [f'    // Font row base {bank_offsets[bank]}, depth {size}.',
                  f'    reg [15:0] pixels{bank} [0:{size-1}]; /* fehdl force_ram=1, ram_style="bram" */',
                  f'    reg [15:0] row{bank};']
    lines += ['    initial begin']
    font = ImageFont.truetype(args.font, 16)
    atlas = Image.new('RGB', (16 * 40, ((slots+15)//16) * 40), '#202830')
    atlas_draw = ImageDraw.Draw(atlas)
    for i in range(slots):
        tile = Image.new('L', (16, 16))
        if i in glyphs:
            draw = ImageDraw.Draw(tile)
            bounds = draw.textbbox((0, 0), glyphs[i], font=font)
            draw.text(((16 - (bounds[2] - bounds[0])) // 2 - bounds[0],
                       (16 - (bounds[3] - bounds[1])) // 2 - bounds[1]),
                      glyphs[i], font=font, fill=255)
        tile = tile.point(lambda p: 255 if p >= 96 else 0)
        for y in range(16):
            bits = sum((1 << (15 - x)) for x in range(16) if tile.getpixel((x, y)))
            address = i*16+y
            bank = max(b for b, offset in enumerate(bank_offsets) if offset <= address)
            lines.append(f"        pixels{bank}[{address-bank_offsets[bank]}]=16'h{bits:04x};")
        if i in glyphs:
            pos = ((i % 16) * 40, (i // 16) * 40)
            atlas.paste(tile.convert('RGB'), (pos[0] + 12, pos[1] + 3))
            atlas_draw.text((pos[0] + 8, pos[1] + 22), f'{i:02X}', fill='white')
    for address in range(slots*16, sum(banks)):
        bank = len(banks)-1
        lines.append(f"        pixels{bank}[{address-bank_offsets[bank]}]=16'h0000;")
    lines += ['    end']
    for bank, size in enumerate(banks):
        lines.append(f'    always @(posedge clk) row{bank}<=pixels{bank}[address[{size.bit_length()-2}:0]];')
    if len(banks) == 1:
        lines += ['    assign row=row0;']
    else:
        lines += ['    reg [2:0] bank_q;', '    always @(posedge clk) begin']
        for bank in range(len(banks)-1, 0, -1):
            prefix = 'if' if bank == len(banks)-1 else 'else if'
            lines.append(f"        {prefix}(address>=13'd{bank_offsets[bank]}) bank_q<=3'd{bank};")
        lines += ["        else bank_q<=0;", '    end']
        expr = ''.join(f"bank_q==3'd{bank} ? row{bank} : " for bank in range(len(banks)-1))
        lines += [f'    assign row={expr}row{len(banks)-1};']
    lines += ['endmodule', '',
              'module subtitle_unicode_map (input wire [15:0] codepoint, output reg [8:0] glyph);',
              '    always @* begin', "        glyph=9'h03f;", "        if(codepoint>=32 && codepoint<=126) glyph={1'b0,codepoint[7:0]};",
              '        else case(codepoint)']
    for c in chinese:
        lines.append(f"            16'h{ord(c):04x}: glyph=9'h{ids[c]:03x}; // {c}")
    lines += ["            default: glyph=9'h03f;", '        endcase', '    end', 'endmodule', '']
    # UART has hundreds of clocks between bytes. Search a compact 9-bit-indexed
    # table instead of parallel comparisons against every 16-bit Unicode value.
    lines += ['module subtitle_unicode_lookup(input wire clk, rst, start,',
              '    input wire [15:0] codepoint, output reg busy, done,',
              '    output reg [8:0] glyph);',
              '    reg [15:0] key;', '    reg [9:0] low, high;',
              '    wire [9:0] middle=(low+high)>>1;',
              '    reg [24:0] entry;', '    always @* begin',
              "        case(middle[8:0])"]
    for index, c in enumerate(chinese):
        lines.append(f"            9'd{index}: entry={{16'h{ord(c):04x},9'h{ids[c]:03x}}};")
    lines += ["            default: entry={16'hffff,9'h03f};", '        endcase', '    end',
              '    always @(posedge clk or posedge rst) begin',
              "        if(rst) begin key<=0;low<=0;high<=0;busy<=0;done<=0;glyph<=9'h03f;end",
              '        else begin', '            done<=0;',
              f"            if(start && !busy) begin key<=codepoint;low<=0;high<=10'd{len(chinese)};busy<=1;end",
              '            else if(busy) begin',
              "                if(low>=high) begin busy<=0;done<=1;glyph<=9'h03f;end",
              '                else if(key==entry[24:9]) begin busy<=0;done<=1;glyph<=entry[8:0];end',
              "                else if(key>entry[24:9]) low<=middle+1'b1;",
              '                else high<=middle;', '            end', '        end', '    end',
              'endmodule', '',
              'module subtitle_default_text (input wire clk, input wire [7:0] address,',
              '    output reg [8:0] glyph, output wire [8:0] length);',
              f"    assign length=9'd{len(text)};", '    always @(posedge clk) begin', '        case(address)']
    for i, c in enumerate(text):
        lines.append(f"            8'd{i}: glyph<=9'h{ids[c]:03x}; // {c}")
    lines += ["            default: glyph<=9'h020;", '        endcase', '    end', 'endmodule', '']
    if opening:
        lines += ['module opening_text_rom(input wire clk, input wire [7:0] address, output reg [8:0] glyph);',
                  '    reg [8:0] text_rom [0:255]; /* fehdl force_ram=1, ram_style="bram" */', '    initial begin']
        for i in range(256):
            line, col = divmod(i,32)
            char = opening[line][col] if line<6 and col<len(opening[line]) else ' '
            lines.append(f"        text_rom[{i}]=9'h{ids[char]:03x};")
        lines += ['    end', '    always @(posedge clk) glyph<=text_rom[address];', 'endmodule', '']
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text('\n'.join(lines), encoding='utf-8')
    if args.preview:
        atlas.save(args.preview)
    print(f'Generated {args.output}: {len(text)} default characters, {len(chinese)} extra glyphs, {slots} slots, {slots*256} font bits')


if __name__ == '__main__':
    main()
